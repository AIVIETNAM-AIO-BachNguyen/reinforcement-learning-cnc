import { test, expect } from '@playwright/test';
import { writeFile } from 'node:fs/promises';
import path from 'node:path';
import { createRequire } from 'node:module';
import type { Job, EvaluationResult } from '../types/generated/scenario-planning';

test('real saved scenario, physical and weight sweeps, replay, reload and immutable LIVE schedule', async ({page}) => {
  test.setTimeout(180000);
  const api = process.env.OPERATIONS_E2E_API_URL!;
  const factory = process.env.OPERATIONS_E2E_FACTORY_ID!;
  const database = new URL(process.env.OPERATIONS_E2E_DATABASE_URL!);
  expect(database.pathname).toMatch(/_(ci|test)$/);
  expect(database.searchParams.get('schema')).toMatch(/^product_api_it_browser_/);
  const backendRequire = createRequire(path.resolve('../backend/package.json'));
  const { PrismaClient } = backendRequire('@prisma/client');
  const db = new PrismaClient({datasources: {db: {url: database.toString()}}});
  const assertions: string[] = [];
  try {
    const head = await db.operationsHead.findUnique({where: {factoryId: factory}});
    const publicationCount = await db.operationSchedule.count({where: {factoryId: factory}});
    await page.goto('/login');
    await page.getByLabel('Username').fill('admin');
    await page.getByLabel('Password', {exact: true}).fill(process.env.OPERATIONS_E2E_ADMIN_PASSWORD!);
    await page.getByRole('button', {name: 'Sign in', exact: true}).click();
    await expect(page).not.toHaveURL(/\/login/);
    await page.goto(`/operations/scenarios?factory_id=${factory}`);
    await page.getByRole('button', {name: 'Create workspace', exact: true}).click();
    await page.getByLabel('Workspace name', {exact: true}).fill('Real Scenario acceptance');
    await page.getByRole('button', {name: 'Review workspace baseline'}).click();
    await page.getByRole('button', {name: 'Create reviewed workspace'}).click();
    await expect(page).toHaveURL(/\/operations\/scenarios\/[a-f0-9-]+/);
    const workspace = new URL(page.url()).pathname.split('/').at(-1)!;
    await expect(page.getByRole('heading', {name: 'Pinned baseline', exact: true})).toBeVisible();
    await page.getByLabel('Scenario name', {exact: true}).fill('Ninety minute maintenance');
    await page.getByRole('button', {name: 'Add assumption', exact: true}).click();
    await page.getByLabel('Assumption 1 duration').fill('90');
    await page.getByRole('button', {name: 'Review draft changes'}).click();
    await page.getByRole('button', {name: 'Save reviewed draft'}).click();
    await expect(page).toHaveURL(/scenario_id=/);
    await page.getByRole('button', {name: 'Run saved scenario', exact: true}).click();
    await expect(page).toHaveURL(/run_id=/);
    const runId = new URL(page.url()).searchParams.get('run_id')!;
    await expect(page.getByRole('region', {name: 'Evaluated scenario'})).toBeVisible({timeout: 60000});
    await expect(page.getByRole('table', {name: 'Computed strategy ranking'})).toBeVisible();
    const read = async (suffix: string): Promise<Job> => {
      const response = await page.request.get(`${api}/api/v1/scenario-workspaces/${workspace}${suffix}`);
      expect(response.status()).toBe(200);
      return (await response.json()).data;
    };
    const first = await read(`/runs/${runId}`);
    const result = first.result as EvaluationResult;
    expect(first.status).toBe('SUCCEEDED');
    expect(result.scenario.outcome).toBe('FEASIBLE');
    expect(result.effective.diff.some(diff => diff.field === 'expected_duration_minutes' && diff.after === 90)).toBe(true);
    expect(result.scenario.candidates!.every(candidate => candidate.validation?.verdict === 'VALID')).toBe(true);
    assertions.push('typed_override_changes_effective_input_and_real_validated_schedule');
    const saved = await db.$queryRawUnsafe('SELECT result_json,result_hash FROM scenario_jobs WHERE id=$1::uuid', runId);
    expect(saved[0].result_json).toEqual(result);
    assertions.push('browser_result_matches_postgresql_accepted_result');
    await page.reload();
    await expect(page.getByRole('region', {name: 'Evaluated scenario'})).toBeVisible();
    expect((await read(`/runs/${runId}`)).result).toEqual(result);
    assertions.push('reload_recovers_saved_result_without_enqueue');
    await page.getByRole('button', {name: 'Run saved scenario', exact: true}).click();
    await expect.poll(() => new URL(page.url()).searchParams.get('run_id')).not.toBe(runId);
    const replayId = new URL(page.url()).searchParams.get('run_id')!;
    await expect(page.getByRole('region', {name: 'Evaluated scenario'})).toBeVisible();
    await expect.poll(async () => (await read(`/runs/${replayId}`)).status).toBe('SUCCEEDED');
    const replay = (await read(`/runs/${replayId}`)).result as EvaluationResult;
    expect(replay.scenario).toEqual(result.scenario);
    expect(replay.semantic_input_hash).toBe(result.semantic_input_hash);
    assertions.push('independent_run_uuid_replays_identical_schedule_and_kpis');
    // Read the completed run summary before reviewing a saved-source sweep.
    await page.reload();
    const sensitivity = page.getByRole('region', {name: 'Sensitivity analysis'});
    await sensitivity.getByRole('button', {name: 'Review sweep inputs'}).click();
    await sensitivity.getByRole('button', {name: 'Start sensitivity job'}).click();
    await expect(page.getByRole('region', {name: 'Evaluated sensitivity'})).toBeVisible({timeout: 60000});
    const physicalId = new URL(page.url()).searchParams.get('sensitivity_id')!;
    const physical = await read(`/sensitivity-jobs/${physicalId}`);
    expect(physical.points).toHaveLength(5);
    expect(physical.status).toBe('SUCCEEDED');
    assertions.push('five_physical_points_replan_and_persist_all_outcomes');
    await sensitivity.getByLabel('Sweep parameter').selectOption('OBJECTIVE_WEIGHT');
    await sensitivity.getByRole('button', {name: 'Review sweep inputs'}).click();
    await sensitivity.getByRole('button', {name: 'Start sensitivity job'}).click();
    await expect.poll(() => new URL(page.url()).searchParams.get('sensitivity_id')).not.toBe(physicalId);
    const weightId = new URL(page.url()).searchParams.get('sensitivity_id')!;
    await expect.poll(async () => (await read(`/sensitivity-jobs/${weightId}`)).status).toBe('SUCCEEDED');
    const sweep = await read(`/sensitivity-jobs/${weightId}`);
    if (!sweep.result || !('points' in sweep.result)) throw new Error('Expected typed sensitivity result');
    expect(sweep.result.points.every(point => JSON.stringify(point.evaluation.candidates) === JSON.stringify(result.scenario.candidates))).toBe(true);
    assertions.push('five_weight_points_keep_candidate_schedules_and_kpis');
    await page.getByRole('button', {name: 'Run baseline', exact: true}).click();
    await expect.poll(() => new URL(page.url()).searchParams.get('run_id')).not.toBe(replayId);
    const baselineId = new URL(page.url()).searchParams.get('run_id')!;
    await expect.poll(async () => (await read(`/runs/${baselineId}`)).status).toBe('SUCCEEDED');
    await page.reload();
    await page.getByRole('checkbox', {name: `Compare run ${baselineId}`, exact: true}).check();
    const comparisonResponse = page.waitForResponse(response => response.url().includes(`/scenario-workspaces/${workspace}/compare`));
    await page.getByRole('checkbox', {name: `Compare run ${runId}`, exact: true}).check();
    const comparison = await comparisonResponse;
    expect(comparison.status()).toBe(200);
    await expect(page.getByRole('region', {name: 'Saved run comparison'}).getByRole('table', {name: 'Computed KPI comparison'}).first()).toBeVisible();
    assertions.push('saved_baseline_and_scenario_compare_through_real_engine');
    expect(await db.operationsHead.findUnique({where: {factoryId: factory}})).toEqual(head);
    expect(await db.operationSchedule.count({where: {factoryId: factory}})).toBe(publicationCount);
    assertions.push('simulation_does_not_change_live_head_or_publication');
    const events = await db.$queryRawUnsafe('SELECT type FROM scenario_events WHERE workspace_id=$1::uuid ORDER BY sequence', workspace);
    expect(events.filter((event: {type: string}) => event.type === 'JOB_SUCCEEDED')).toHaveLength(5);
    assertions.push('five_completed_jobs_have_durable_audit_events');
    await page.screenshot({path: test.info().outputPath('real-scenario-completed.png'), fullPage: true});
    await writeFile(path.join(path.dirname(process.env.OPERATIONS_E2E_EVIDENCE_FILE!), 'scenario-evidence.json'), JSON.stringify({
      git_sha: process.env.OPERATIONS_E2E_GIT_SHA, source_tree_dirty: process.env.OPERATIONS_E2E_SOURCE_DIRTY === 'true',
      run: Number(process.env.OPERATIONS_E2E_RUN), workspace_id: workspace, run_id: runId,
      semantic_input_hash: result.semantic_input_hash, assertions_passed: assertions,
    }, null, 2));
  } finally { await db.$disconnect(); }
});
